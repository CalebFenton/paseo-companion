import { readFileSync } from "node:fs";
import { expect, it } from "vitest";
import { z } from "zod";
import { RANGES } from "../../shared/system";
import { createHistory, type Row, rowSchema } from "./history";
import { busiestProcesses, measure, type ProcFiles, parseMounts, parseProc, parseProcesses, type Sample, topProcess } from "./proc";
import { buildSystemView, pointOf } from "./view";

const procFilesSchema = z.object({
  stat: z.string(),
  meminfo: z.string(),
  loadavg: z.string(),
  diskstats: z.string(),
  netDev: z.string(),
  pressure: z.object({ cpu: z.string(), memory: z.string(), io: z.string() }).nullable(),
});
const processReadSchema = z.object({ at: z.number(), files: z.object({ stat: z.string(), processes: z.record(z.string(), z.string()) }) });
const statsSchema = z.object({
  bsize: z.number(),
  blocks: z.number(),
  bfree: z.number(),
  bavail: z.number(),
  files: z.number(),
  ffree: z.number(),
});

/**
 * Three real /proc reads 2 seconds apart, the last two samples straddling a minute, beside six
 * hours of persisted minutes with a spike and a 40-minute outage, and this host's mounts with each
 * one's statfs, null where it failed; then two reads of busy, idle, and newly started processes 10
 * seconds apart, with the busiest ones' details, and Paseo workspaces some of them run in;
 * generated by a script outside the repo.
 */
const input = z
  .object({
    host: z.string(),
    now: z.number(),
    views: z.array(z.object({ range: z.enum(RANGES), bars: z.number() })),
    reads: z.array(z.object({ at: z.number(), files: procFilesSchema })),
    minutes: z.array(rowSchema),
    mountinfo: z.string(),
    statfs: z.record(z.string(), z.object({ at: z.number(), stats: statsSchema }).nullable()),
    processes: z.object({
      reads: z.tuple([processReadSchema, processReadSchema]),
      details: z.record(
        z.string(),
        z.object({ status: z.string().nullable(), cmdline: z.string().nullable(), cwd: z.string().nullable() }),
      ),
      workspaces: z.unknown(),
      home: z.string(),
    }),
  })
  .parse(JSON.parse(readFileSync(new URL("../../fixtures/system.input.json", import.meta.url), "utf8")));

/** Arrays of plain values on one line each, so bars read as rows. */
function golden(value: unknown): string {
  const marked = JSON.stringify(
    value,
    (_key, entry: unknown) =>
      Array.isArray(entry) && entry.every((item) => item === null || typeof item !== "object") ? `\u0000${JSON.stringify(entry)}` : entry,
    2,
  );
  return `${marked.replaceAll(/"\\u0000((?:[^"\\]|\\.)*)"/g, (_match, inner: string) => z.string().parse(JSON.parse(`"${inner}"`)))}\n`;
}

/** What the monitor makes of the recorded reads: the minutes they close, and the view input before a request. */
function record() {
  const counters = input.reads.map(({ at, files }) => parseProc(files, at));
  const history = createHistory(input.minutes);
  const closed: Row[] = [];
  let latest: Sample | null = null;
  for (const [index, after] of counters.entries()) {
    const before = counters[index - 1];
    if (!before) continue;
    latest = measure(before, after);
    const minute = history.add(latest.at, pointOf(latest));
    if (minute) closed.push(minute);
  }
  const filesystems = parseMounts(input.mountinfo).flatMap((mount) => {
    const read = input.statfs[mount.path];
    return read ? [{ ...mount, ...read }] : [];
  });
  const [first, second] = input.processes.reads;
  const before = parseProcesses(first.files, first.at);
  const after = parseProcesses(second.files, second.at);
  const processes = {
    seconds: (after.at - before.at) / 1000,
    top: busiestProcesses(before, after, 10).map((busy) =>
      topProcess(busy, input.processes.details[busy.pid] ?? { status: null, cmdline: null, cwd: null }),
    ),
    workspaces: input.processes.workspaces,
    home: input.processes.home,
  };
  return { closed, base: { host: input.host, latest, history, filesystems, processes, now: input.now, error: null } };
}

/** The minutes the recorded reads close, and the view of each recorded request. */
function replay() {
  const { closed, base } = record();
  return { closed, views: input.views.map((request) => buildSystemView({ ...base, request })) };
}

// A change detector: the expected view was captured from this code, so it proves sameness, not correctness.
it("turns /proc reads and persisted minutes into the recorded system view", async () => {
  await expect(golden(replay())).toMatchFileSnapshot("../../fixtures/system.view.json");
});

/** The recorded view's second headline reading, with the last sample's one-minute load set to `one`. */
function secondReading(one: number) {
  const { base } = record();
  if (!base.latest) throw new Error("The recorded reads close no sample");
  return buildSystemView({ ...base, latest: { ...base.latest, load: { ...base.latest.load, one } }, request: null }).headline?.[1];
}

it("names load in the sidebar headline in place of memory once load is the worse reading", () => {
  // The recorded host has 60 cores and 27% memory in use: load warns from 120 (two per core).
  expect(secondReading(119)).toEqual({ text: "mem 27%", tone: "ok" });
  expect(secondReading(150)).toEqual({ text: "load 150", tone: "warning" });
});

/** /proc files of a host with nothing to read but `stat` and `diskstats`. */
function procFiles(stat: string, diskstats = ""): ProcFiles {
  return { stat, meminfo: "", loadavg: "0 0 0 1/100 1", diskstats, netDev: "", pressure: null };
}

/** major minor name reads merged sectors-read ms writes merged sectors-written …: `sectors` read from sda, the same through sda1. */
function sdaDiskstats(sectors: number): string {
  return [`   8       0 sda 10 0 ${sectors} 0 0 0 0 0 0 0 0`, `   8       1 sda1 10 0 ${sectors} 0 0 0 0 0 0 0 0`].join("\n");
}

it("counts iowait as idle, not busy", () => {
  // user nice system idle iowait irq softirq steal: 30 user, 10 system, 20 idle, and 40 iowait jiffies between the reads.
  const sample = measure(parseProc(procFiles("cpu  100 0 50 800 0 0 0 0"), 0), parseProc(procFiles("cpu  130 0 60 820 40 0 0 0"), 2_000));
  expect(sample.cpu.busy).toBeCloseTo(40);
  expect(sample.cpu.iowait).toBeCloseTo(40);
});

it("counts a disk's bytes once, not again through its partition", () => {
  const stat = "cpu  0 0 0 0 0 0 0 0";
  const sample = measure(parseProc(procFiles(stat, sdaDiskstats(1_000)), 0), parseProc(procFiles(stat, sdaDiskstats(3_000)), 2_000));
  // 2,000 sectors of 512 bytes over 2 seconds.
  expect(sample.disk).toEqual({ read: 512_000, written: 0 });
});

it("undoes the kernel's octal escapes in mount paths", () => {
  const mountinfo = "36 25 8:17 / /mnt/backup\\040disk rw,relatime shared:1 - ext4 /dev/sdb1 rw,errors=remount-ro\n";
  expect(parseMounts(mountinfo)).toEqual([{ path: "/mnt/backup disk", type: "ext4", source: "/dev/sdb1" }]);
});

it("counts used space as df does: of the space users can fill, root's reserve left out", () => {
  // 1,000 blocks: 300 free, of which 200 users can fill; so 700 used of 900, not 70% of all blocks, nor 80% short of available.
  const stats = { bsize: 4096, blocks: 1_000, bfree: 300, bavail: 200, files: 0, ffree: 0 };
  const view = buildSystemView({
    host: "host",
    latest: null,
    history: createHistory([]),
    filesystems: [{ path: "/", type: "ext4", source: "/dev/sda1", at: 0, stats }],
    processes: null,
    request: null,
    now: 0,
    error: null,
  });
  expect(view.filesystems.map(({ value, fraction }) => ({ value, fraction }))).toEqual([{ value: "78%", fraction: 0.778 }]);
});
